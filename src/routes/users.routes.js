import { Router } from "express";
import c from "../controllers/users.controller.js";
import { uploadUserDocument } from "../middlewares/upload.middleware.js";
const r=Router();
r.get("/",c.getAll);
r.get("/:id",c.getById);
r.post("/",c.create);
r.put("/:id",c.update);
r.delete("/:id",c.delete);
r.post("/:id/document",uploadUserDocument.single("file"),c.document);
export default r;
